// Result LoadProfileImage(size_t *size, void *buf, size_t bufSize, const Uid &)
static void load_profile_image(Cpu *c) {
    uint64_t *n = arg_p(c, 0), size = arg_x(c, 2);
    uint8_t *buf = arg_p(c, 1);
    if (buf) memcpy(buf, profile_jpeg, size < sizeof profile_jpeg ? size : sizeof profile_jpeg);
    if (n) *n = sizeof profile_jpeg;
    ret_x(c, 0);
}
// Result LoadNetworkServiceAccountIdTokenCache(size_t *, char *, size_t, const UserHandle &)
static void no_token(Cpu *c) {
    uint64_t *n = arg_p(c, 0);
    if (n) *n = 0;
    ret_x(c, RES_UNAVAILABLE);
}
// AsyncContext: the host makes no IPC object; the completion event fires at once and the result is a failure
static void async_event(Cpu *c) {
    kern_signal_system_event(arg_x(c, 1));
    ret_x(c, 0);
}
static void async_done(Cpu *c) {
    *(uint8_t *)arg_p(c, 1) = 1;
    ret_x(c, 0);
}
static void async_move(Cpu *c) { ret_x(c, arg_x(c, 0)); }
static void false_out(Cpu *c) {
    *(uint8_t *)arg_p(c, 0) = 0;
    ret_x(c, 0);
}

