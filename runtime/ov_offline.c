#define RES_UNAVAILABLE 0x2A2u   // the generic failure of a network feature that is not there

// A SystemEventType the game waits on, in guest-visible kernel memory, bound once and never signalled.
#define SYSTEM_EVENT_BYTES 0x100
static PlatMutex lock = PLAT_MUTEX_INIT;

static uint64_t quiet_event(Cpu *c, uint64_t *slot) {
    plat_mutex_lock(&lock);
    if (!*slot) {
        *slot = (uint64_t)(uintptr_t)mem_kernel_alloc(SYSTEM_EVENT_BYTES, 16);
        kern_bind_system_event(c, *slot, 0);
    }
    uint64_t ev = *slot;
    plat_mutex_unlock(&lock);
    return ev;
}

static uint64_t notify_event, invite_event;

static void nothing(Cpu *c) { (void)c; }
static void unavailable(Cpu *c) { ret_x(c, RES_UNAVAILABLE); }
static void none(Cpu *c) { ret_x(c, 0); }   // bool false / count 0

// Result GetFriendList(int *count, Friend *out, const Uid &, int offset, int n, const FriendFilter &): empty
static void friend_list(Cpu *c) {
    int *count = arg_p(c, 0);
    if (count) *count = 0;
    ret_x(c, RES_UNAVAILABLE);
}
static void notification_event(Cpu *c) { ret_x(c, quiet_event(c, &notify_event)); }
static void invitation_event(Cpu *c) { ret_x(c, quiet_event(c, &invite_event)); }

